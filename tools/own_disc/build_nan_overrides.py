"""The iOS build's NaN overrides, made from this run's shader pack: SPIR-V modules whose clamped RSQ stays finite under
Metal fast math.

    build_nan_overrides.py --pack PACK --spirv-tools DIR --out NEW_DIR

The v41 shader translator emits the console's RSQ as FClamp(InverseSqrt(x), -FLT_MAX, FLT_MAX). MoltenVK compiles with
Metal fast math, which may drop the clamp of +inf; where x = 0 and the result multiplies a zero vector, 0 x inf = NaN (the
iOS phone composite's pale band, DISCOVERIES 2026-10-22). Each SCALAR instance becomes InverseSqrt(FMax(x, FLT_MIN)):
identical for every normal x, finite for x = 0, so 0 x it stays 0. Modules: KEYS below, read from PACK (the shader-select
stage's generic-shaders.bin, made from the player's discs); nothing game-derived is held here.
For each module: spirv-dis --raw-id; a control (the unmodified text reassembles to the same module, word 2 aside: the
generator id); the patch; spirv-as --target-env spv1.3; spirv-val --target-env vulkan1.1. DIR holds the NDK's spirv-dis,
spirv-as and spirv-val. Written: NEW_DIR/generic_nan_overrides.inc ({key, words, code}: the DenormOverride layout the
runtime's reglod::apply takes) and NEW_DIR/report.json. The same algorithm as the iOS session's make_nan_overrides.py
(2026-10-22), whose table the iOS build compiles; the kit fills that file's first line (a comment) itself.
Exit 0: written; 2: refused (a module missing, a control that differs, nothing to patch, an invalid module).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

KEYS = {0xe2649e6bc8ee4db8: 'phone composite (pass 110)', 0xf0ff7fe255dbc811: 'minimap composite (im#41p)'}
FLT_MIN = '1.17549435e-38'
FIRST_LINE = '// Generated by tools/own_disc/build_nan_overrides.py from this run\'s shader pack (game-derived; do not edit).'


class Refusal(Exception):
    pass


def modules(pack: bytes) -> dict[int, tuple[int, bytes]]:
    _magic, _version, count, _reserved = struct.unpack_from('<4sIII', pack, 0)
    out = {}
    for i in range(count):
        key, stage, off, words, _n = struct.unpack_from('<QIIII', pack, 16 + i * 152)
        if key in KEYS:
            out[key] = (stage, pack[off:off + words * 4])
    return out


def patch(text: str) -> tuple[str, int, int]:
    ext = re.search(r'^\s*(%\w+) = OpExtInstImport "GLSL.std.450"', text, re.M).group(1)
    ftype = re.search(r'^\s*(%\w+) = OpTypeFloat 32$', text, re.M).group(1)
    out, n, skipped = [], 0, 0
    for ln in text.splitlines():
        m = re.match(r'^(\s*)(%\w+) = OpExtInst (%\w+) ' + re.escape(ext) + r' InverseSqrt (%\w+)$', ln)
        if m and re.search(r'= OpExtInst %\w+ ' + re.escape(ext) + r' FClamp ' + re.escape(m.group(2)) + r' ', text):
            if m.group(3) != ftype:                     # a vector RSQ: left as it is
                skipped += 1
                out.append(ln)
                continue
            n += 1
            tmp = f'%nanfix_{n}'
            out.append(f'{m.group(1)}{tmp} = OpExtInst {ftype} {ext} FMax {m.group(4)} %nanfix_fltmin')
            out.append(f'{m.group(1)}{m.group(2)} = OpExtInst {ftype} {ext} InverseSqrt {tmp}')
            continue
        out.append(ln)
        if ln.strip() == f'{ftype} = OpTypeFloat 32':
            out.append(f'%nanfix_fltmin = OpConstant {ftype} {FLT_MIN}')
    return '\n'.join(out) + '\n', n, skipped


def build(pack_path: Path, tools: Path, out: Path) -> dict:
    exe = '.exe' if os.name == 'nt' else ''
    dis, asm, val = (tools / f'spirv-{t}{exe}' for t in ('dis', 'as', 'val'))
    for t in (dis, asm, val):
        if not t.is_file():
            raise Refusal(f'{t.name} is not in {tools}')
    pack = pack_path.read_bytes()
    found = modules(pack)
    missing = [f'{k:016x}' for k in KEYS if k not in found]
    if missing:
        raise Refusal(f'the pack has no module {", ".join(missing)}')
    arrays, rows, report = [], [], []
    with tempfile.TemporaryDirectory() as tmp:
        w = Path(tmp)
        for key, name in KEYS.items():
            stage, spv = found[key]
            tag = f'{key:016x}'
            (w / f'{tag}.spv').write_bytes(spv)
            text = subprocess.run([str(dis), '--raw-id', str(w / f'{tag}.spv')], capture_output=True, text=True, check=True).stdout
            (w / f'{tag}.orig.spvasm').write_text(text, encoding='utf-8')
            subprocess.run([str(asm), '--target-env', 'spv1.3', str(w / f'{tag}.orig.spvasm'), '-o', str(w / f'{tag}.ctrl.spv')],
                           check=True)
            ctrl = bytearray((w / f'{tag}.ctrl.spv').read_bytes())
            ctrl[8:12] = spv[8:12]
            if bytes(ctrl) != spv:
                raise Refusal(f'{tag}: the control differs (disassembly and reassembly do not give the module back)')
            new, n, skipped = patch(text)
            if n == 0:
                raise Refusal(f'{tag}: no scalar clamped InverseSqrt')
            (w / f'{tag}.nan.spvasm').write_text(new, encoding='utf-8')
            subprocess.run([str(asm), '--target-env', 'spv1.3', str(w / f'{tag}.nan.spvasm'), '-o', str(w / f'{tag}.nan.spv')],
                           check=True)
            v = subprocess.run([str(val), '--target-env', 'vulkan1.1', str(w / f'{tag}.nan.spv')], capture_output=True, text=True)
            if v.returncode:
                raise Refusal(f'{tag}: spirv-val: {v.stderr.strip()[:300]}')
            code = bytearray((w / f'{tag}.nan.spv').read_bytes())
            code[8:12] = spv[8:12]
            words = len(code) // 4
            arrays.append(f'static const std::uint32_t NanOverride{len(rows)}[]={{'
                          + ','.join(f'0x{x:08x}' for x in struct.unpack(f'<{words}I', bytes(code))) + '};')
            rows.append(f'    {{0x{key:016x}ull,{words}u,NanOverride{len(rows)}}}, // {name}')
            report.append({'key': tag, 'name': name, 'stage': stage, 'patched': n, 'vector_skipped': skipped,
                           'words_in': len(spv) // 4, 'words_out': words})
    inc = [FIRST_LINE,
           '// Pack modules whose clamped RSQ (FClamp(InverseSqrt(x), +-FLT_MAX)) turns into NaN under Metal fast math; '
           'InverseSqrt(FMax(x, FLT_MIN)).',
           *arrays, 'static const DenormOverride NanOverrides[]={', *rows, '};']
    out.mkdir(parents=True)
    (out / 'generic_nan_overrides.inc').write_bytes(('\n'.join(inc) + '\n').encode('utf-8'))
    record = {'schema': 'nan-overrides/1', 'pack_sha256': hashlib.sha256(pack).hexdigest(), 'modules': report,
              'inc_sha256': hashlib.sha256((out / 'generic_nan_overrides.inc').read_bytes()).hexdigest()}
    (out / 'report.json').write_bytes((json.dumps(record, indent=1) + '\n').encode('utf-8'))
    return record


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--pack', type=Path, required=True)
    ap.add_argument('--spirv-tools', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args(argv)
    if a.out.exists():
        print(f'REFUSED: {a.out} exists', file=sys.stderr)
        return 2
    try:
        record = build(a.pack, a.spirv_tools, a.out)
    except (Refusal, OSError, subprocess.CalledProcessError) as error:
        print(f'REFUSED: {error}', file=sys.stderr)
        return 2
    for m in record['modules']:
        print(f'{m["key"]} {m["name"]}: stage {m["stage"]} rsq patched {m["patched"]} (vector skipped {m["vector_skipped"]}) '
              f'words {m["words_in"]} -> {m["words_out"]} VALID')
    print(f'NAN-OVERRIDES {len(record["modules"])} modules -> {a.out / "generic_nan_overrides.inc"} {record["inc_sha256"][:16]}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
