#pragma once
#include <algorithm>
#include <atomic>
#include <cmath>
#include <cstdint>
#include <limits>

namespace recomp::apple {
inline bool shouldReportAudioSignal(std::uint32_t observed,std::uint32_t previous) noexcept {
    return observed>previous && (!previous || observed-previous>=48000);
}
// Diagnostic metadata only. One AudioUnit callback writer, any number of
// readers. Counts are packed for a coherent lock-free snapshot; each saturates
// after UINT32_MAX frames (~24.9 hours at 48kHz), never wraps into new evidence.
// No samples retained, allocation, locks, logging, or audio changes here.
class AudioSignalEvidence final {
    static_assert(std::atomic<std::uint64_t>::is_always_lock_free);
    std::atomic<std::uint64_t> counts_{0};
    std::atomic<bool> invalid_{false};
public:
    struct Snapshot {std::uint32_t frames, nonzeroFrames; bool invalidSamples;};
    void observe(const float* output, std::uint32_t consumed) noexcept {
        if(!output || !consumed)return;
        std::uint32_t nonzero=0;
        for(std::uint32_t i=0;i<consumed;++i) {
            const float left=output[std::size_t(i)*2],right=output[std::size_t(i)*2+1];
            if(!std::isfinite(left) || !std::isfinite(right))invalid_.store(true,std::memory_order_relaxed);
            else if(left!=0 || right!=0)++nonzero;
        }
#if defined(APPLE_AUDIO_SIGNAL_MUTANT_SILENCE)
        nonzero=consumed;
#endif
        const auto previous=counts_.load(std::memory_order_relaxed);
        constexpr auto maximum=std::numeric_limits<std::uint32_t>::max();
        const auto frames=std::min<std::uint64_t>(maximum,std::uint32_t(previous)+std::uint64_t(consumed));
        const auto signal=std::min<std::uint64_t>(maximum,(previous>>32)+nonzero);
        counts_.store(frames|(signal<<32),std::memory_order_release);
    }
    Snapshot snapshot() const noexcept {
        const auto value=counts_.load(std::memory_order_acquire);
        return {std::uint32_t(value),std::uint32_t(value>>32),invalid_.load(std::memory_order_relaxed)};
    }
};

// This is the exact ring -> AudioUnit output boundary. Never observe queued
// producer input: it may be backpressured or never actually consumed. Underrun
// silence was generated by the host, so it is explicitly excluded from counts.
template<class Ring>
std::uint32_t renderAudioObserved(Ring& ring,float* output,std::uint32_t frames,
                                 AudioSignalEvidence* evidence) noexcept {
    const auto consumed=ring.render(output,frames);
    if(evidence) {
#if defined(APPLE_AUDIO_SIGNAL_MUTANT_UNDERRUN)
        evidence->observe(output,frames);
#else
        evidence->observe(output,consumed);
#endif
    }
    return consumed;
}
}
